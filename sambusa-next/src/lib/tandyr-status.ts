import type { TandyrStatus } from "@/types/store";

export function getTandyrStatusLabel(status: TandyrStatus): string {
  switch (status) {
    case "hot":
      return "\u0422\u0430\u043d\u0434\u044b\u0440 \u0433\u043e\u0440\u044f\u0447\u0438\u0439 \u00b7 \u0421\u0430\u043c\u043e\u0432\u044b\u0432\u043e\u0437 \u0437\u0430 15\u201320 \u043c\u0438\u043d";
    case "baking":
      return "\u041f\u0435\u0447\u0451\u043c \u0441\u0432\u0435\u0436\u0443\u044e \u043f\u0430\u0440\u0442\u0438\u044e";
    case "closed":
      return "\u041f\u0435\u043a\u0430\u0440\u043d\u044f \u0437\u0430\u043a\u0440\u044b\u0442\u0430";
    default:
      return "\u0422\u0430\u043d\u0434\u044b\u0440 \u0433\u043e\u0440\u044f\u0447\u0438\u0439 \u00b7 \u0421\u0430\u043c\u043e\u0432\u044b\u0432\u043e\u0437 \u0437\u0430 15\u201320 \u043c\u0438\u043d";
  }
}

